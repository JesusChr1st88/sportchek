/* Структура фулбоди по числу упражнений на тренировку.
   Каждая крупная группа — в каждой тренировке (3 раза в неделю: по данным Schoenfeld 2016,
   частота 2+ раза в неделю на группу лучше одного), мелкие чередуются по дням.
   'arms' — бицепс/трицепс по очереди, 'extra' — пресс/икры по очереди.            */
export const FB_SLOTS = {
  6: ['quads', 'chest', 'back', 'post', 'delts', 'arms'],
  7: ['quads', 'chest', 'back', 'post', 'delts', 'arms', 'extra'],
  8: ['quads', 'chest', 'back', 'post', 'delts', 'biceps', 'triceps', 'extra']
};
const ROTATE = { arms: ['triceps', 'biceps', 'triceps'], extra: ['core', 'calves', 'core'] };

const norm = s => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
export const libByGroup = g => LIB.filter(e => e[1] === g);
export const libFind = name => LIB.find(e => norm(e[0]) === norm(name));

// Состав дня фулбоди: для каждой группы — своё упражнение в каждый из дней
export function fullbodyPlan(count, days = 3) {
  const slots = FB_SLOTS[count] || FB_SLOTS[7];
  return Array.from({ length: days }, (_, d) => slots.map(sl => {
    const g = ROTATE[sl] ? ROTATE[sl][d % ROTATE[sl].length] : sl;
    const list = libByGroup(g);
    // жим лёжа — только в первый день: тяжёлой базе нужен отдых
    return list[d % list.length];
  }));
}

// Группа по названию для упражнений вне библиотеки
export function guessGroup(name) {
  const hit = libFind(name);
  if (hit) return hit[1];
  const k = norm(name);
  if (/разгибания ног|жим.*ног|платформ|выпад|присед/.test(k)) return 'quads';
  if (/сгибания ног|ягодич|мост|отведени|румынск|становая/.test(k)) return 'post';
  if (/носки|икр/.test(k)) return 'calves';
  if (/бицепс|молот|сгибания на блоке|сгибания рук/.test(k)) return 'biceps';
  if (/трицепс|разгибания рук|француз|из-за головы|брусья/.test(k)) return 'triceps';
  if (/мах|дельт|разведени|жим .*(стоя|сидя)|45°|армейский/.test(k)) return 'delts';
  if (/тяга|подтяг|пуловер/.test(k)) return 'back';
  if (/жим|сведени|отжим|грудь/.test(k)) return 'chest';
  if (/скруч|планк|пресс/.test(k)) return 'core';
  return 'other';
}
